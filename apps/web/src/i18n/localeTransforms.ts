export function toTraditionalText(value: string): string {
  let output = value;
  for (const [from, to] of phraseReplacements) {
    output = output.split(from).join(to);
  }
  return Array.from(output, (char) => simplifiedToTraditional[char] || char).join("");
}

export function toTraditionalDeep<T>(value: T): T {
  if (typeof value === "string") return toTraditionalText(value) as T;
  if (Array.isArray(value)) return value.map((item) => toTraditionalDeep(item)) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([key, item]) => [key, toTraditionalDeep(item)])
    ) as T;
  }
  return value;
}

type MessageTree = Record<string, unknown>;

export function mergeMessages<T extends MessageTree>(base: T, overrides: Partial<T>): T {
  if (!overrides || typeof overrides !== "object") return base;
  const output: MessageTree = { ...base };
  for (const [key, value] of Object.entries(overrides)) {
    const baseValue = output[key];
    if (
      baseValue &&
      value &&
      typeof baseValue === "object" &&
      typeof value === "object" &&
      !Array.isArray(baseValue) &&
      !Array.isArray(value)
    ) {
      output[key] = mergeMessages(baseValue as MessageTree, value as Partial<MessageTree>);
    } else {
      output[key] = value;
    }
  }
  return output as T;
}

export function localizedText(en: string, zhCN: string, ms: string, zhTW?: string): LocalizedText {
  return {
    en,
    ms,
    "zh-CN": zhCN,
    "zh-TW": zhTW || toTraditionalText(zhCN)
  };
}

export function localizedArray(en: string[], zhCN: string[], ms: string[], zhTW?: string[]): LocalizedStringArray {
  return {
    en,
    ms,
    "zh-CN": zhCN,
    "zh-TW": zhTW || zhCN.map(toTraditionalText)
  };
}
